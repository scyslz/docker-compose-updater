package main

import (
	"context"
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// inspectContainer is the subset of `docker inspect` output needed to generate
// a compose service. Docker returns an array even for a single container.
type inspectContainer struct {
	Name   string `json:"Name"`
	Config struct {
		Image    string            `json:"Image"`
		Env      []string          `json:"Env"`
		Labels   map[string]string `json:"Labels"`
		Hostname string            `json:"Hostname"`
	} `json:"Config"`
	HostConfig struct {
		RestartPolicy struct {
			Name              string `json:"Name"`
			MaximumRetryCount int    `json:"MaximumRetryCount"`
		} `json:"RestartPolicy"`
		NetworkMode string `json:"NetworkMode"`
	} `json:"HostConfig"`
	Mounts []struct {
		Type        string `json:"Type"`
		Name        string `json:"Name"`
		Source      string `json:"Source"`
		Destination string `json:"Destination"`
		RW          bool   `json:"RW"`
	} `json:"Mounts"`
	NetworkSettings struct {
		Ports map[string][]struct {
			HostIP   string `json:"HostIp"`
			HostPort string `json:"HostPort"`
		} `json:"Ports"`
		Networks map[string]json.RawMessage `json:"Networks"`
	} `json:"NetworkSettings"`
}

// generateComposeFromContainer builds a compose.yaml from a standalone
// container's inspect data. Because the original container keeps running, the
// generated file uses a new container name and new host ports, and keeps the
// original values as comments so it can be started alongside the old container.
func generateComposeFromContainer(ctx context.Context, u *updater, name string) (string, []string, error) {
	out, err := u.runDocker(ctx, "", []string{"inspect", name})
	if err != nil {
		return "", nil, fmt.Errorf("inspect %s: %w", name, err)
	}
	var inspected []inspectContainer
	if err := json.Unmarshal(out, &inspected); err != nil {
		return "", nil, fmt.Errorf("parse inspect output: %w", err)
	}
	if len(inspected) == 0 {
		return "", nil, fmt.Errorf("container %s not found", name)
	}
	c := inspected[0]

	containerName := strings.TrimPrefix(c.Name, "/")
	if containerName == "" {
		containerName = name
	}
	service := serviceName(containerName)
	warnings := []string{}

	newName, err := freeContainerName(ctx, u, containerName)
	if err != nil {
		newName = containerName + "-compose"
		warnings = append(warnings, "could not check existing container names: "+err.Error())
	}

	// Ports published by any container (including this one) are unavailable
	// for the new project, since the old container still holds them.
	occupied, err := occupiedHostPorts(ctx, u)
	if err != nil {
		warnings = append(warnings, "could not check published host ports: "+err.Error())
		occupied = map[int]bool{}
	}

	var b strings.Builder
	b.WriteString("# Generated by compose-auto-updater from standalone container " + strconv.Quote(containerName) + ".\n")
	b.WriteString("# Review before use: volumes, networks, and environment are copied as-is\n")
	b.WriteString("# from `docker inspect`, not from the image's defaults.\n")
	b.WriteString("#\n")
	b.WriteString("# A new container name and new host ports are used so this project can\n")
	b.WriteString("# run alongside the original container. Start it with:\n")
	b.WriteString("#   docker compose -f compose.yaml up -d\n")
	b.WriteString("# After verifying the new service, remove the old container manually:\n")
	b.WriteString("#   docker stop " + containerName + " && docker rm " + containerName + "\n")
	b.WriteString("# The original name and port mappings are kept as comments.\n")
	b.WriteString("services:\n")
	b.WriteString("  " + service + ":\n")
	b.WriteString("    image: " + yamlString(c.Config.Image) + "\n")
	b.WriteString("    # was: " + containerName + "\n")
	b.WriteString("    container_name: " + yamlString(newName) + "\n")

	// Restart policy: keep an explicit policy, otherwise default to
	// unless-stopped, which is what a long-running service usually wants.
	restart := c.HostConfig.RestartPolicy.Name
	switch restart {
	case "", "no":
		b.WriteString("    restart: unless-stopped\n")
		warnings = append(warnings, "the source container had no restart policy; generated `restart: unless-stopped`")
	case "on-failure":
		if n := c.HostConfig.RestartPolicy.MaximumRetryCount; n > 0 {
			b.WriteString("    restart: \"on-failure:" + strconv.Itoa(n) + "\"\n")
		} else {
			b.WriteString("    restart: on-failure\n")
		}
	default:
		b.WriteString("    restart: " + yamlString(restart) + "\n")
	}

	writePorts(&b, c, occupied, &warnings)
	externalVolumes := writeVolumes(&b, c, &warnings)
	writeEnvironment(&b, c)
	writeLabels(&b, c)
	externalNetworks := writeNetwork(&b, c, &warnings)
	// File-level sections must come after every service key.
	writeTopLevelVolumes(&b, externalVolumes)
	writeTopLevelNetworks(&b, externalNetworks)

	if newName != containerName {
		warnings = append(warnings, "new container name: "+newName+" (old: "+containerName+")")
	}
	return b.String(), warnings, nil
}

// writePorts emits published ports as `ports` and unpublished exposed ports as
// `expose`. Each published host port is moved to the next free port because the
// original container still holds the old one; the old mapping is kept as a
// comment on the same line.
func writePorts(b *strings.Builder, c inspectContainer, occupied map[int]bool, warnings *[]string) {
	type published struct {
		spec string
		old  string
	}
	var ports []published
	var exposed []string

	keys := make([]string, 0, len(c.NetworkSettings.Ports))
	for k := range c.NetworkSettings.Ports {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	for _, cport := range keys {
		proto := "tcp"
		port := cport
		if i := strings.IndexByte(cport, '/'); i >= 0 {
			port, proto = cport[:i], cport[i+1:]
		}
		bindings := c.NetworkSettings.Ports[cport]
		if len(bindings) == 0 {
			if proto == "tcp" {
				exposed = append(exposed, port)
			} else {
				exposed = append(exposed, port+"/"+proto)
			}
			continue
		}
		seen := map[string]bool{}
		for _, bind := range bindings {
			if bind.HostPort == "" {
				continue
			}
			oldSpec := composePortSpec(bind.HostIP, bind.HostPort, port, proto)
			if seen[oldSpec] {
				continue
			}
			seen[oldSpec] = true
			hostPort, err := strconv.Atoi(bind.HostPort)
			if err != nil {
				*warnings = append(*warnings, "could not parse host port "+bind.HostPort+"; mapping kept unchanged")
				ports = append(ports, published{spec: oldSpec, old: oldSpec})
				continue
			}
			newPort := nextFreePort(hostPort, occupied)
			occupied[newPort] = true
			spec := composePortSpec(bind.HostIP, strconv.Itoa(newPort), port, proto)
			ports = append(ports, published{spec: spec, old: oldSpec})
			*warnings = append(*warnings, "port "+oldSpec+" -> "+spec+" (old mapping kept as a comment)")
		}
	}

	if len(ports) > 0 {
		b.WriteString("    ports:\n")
		for _, p := range ports {
			line := "      - " + strconv.Quote(p.spec)
			if p.old != p.spec {
				line += "  # was: " + strconv.Quote(p.old)
			}
			b.WriteString(line + "\n")
		}
	}
	if len(exposed) > 0 {
		b.WriteString("    expose:\n")
		for _, e := range exposed {
			b.WriteString("      - " + strconv.Quote(e) + "\n")
		}
	}
}

// nextFreePort returns the first host port after start that is not published by
// any container, wrapping around at the top of the range.
func nextFreePort(start int, occupied map[int]bool) int {
	for p := start + 1; p <= 65535; p++ {
		if p >= 1024 && !occupied[p] {
			return p
		}
	}
	for p := 1024; p < start; p++ {
		if !occupied[p] {
			return p
		}
	}
	return start
}

// writeVolumes reproduces bind mounts and named volumes. Named volumes are
// declared external so the new project reuses the existing data instead of
// creating empty project-prefixed volumes.
func writeVolumes(b *strings.Builder, c inspectContainer, warnings *[]string) []string {
	var mounts []string
	var tmpfs []string
	var rwMounts int
	externalVolumes := map[string]bool{}

	for _, m := range c.Mounts {
		if m.RW && (m.Type == "bind" || m.Type == "volume") {
			rwMounts++
		}
		switch m.Type {
		case "bind":
			if m.Source == "" || m.Destination == "" {
				continue
			}
			spec := m.Source + ":" + m.Destination
			if !m.RW {
				spec += ":ro"
			}
			mounts = append(mounts, spec)
		case "volume":
			if m.Destination == "" {
				continue
			}
			if m.Name == "" {
				// Anonymous volume: keep it as an anonymous volume.
				mounts = append(mounts, m.Destination)
				continue
			}
			spec := m.Name + ":" + m.Destination
			if !m.RW {
				spec += ":ro"
			}
			mounts = append(mounts, spec)
			externalVolumes[m.Name] = true
		case "tmpfs":
			if m.Destination != "" {
				tmpfs = append(tmpfs, m.Destination)
			}
		default:
			if m.Destination != "" {
				*warnings = append(*warnings, "skipped mount of unsupported type "+strconv.Quote(m.Type)+" at "+m.Destination)
			}
		}
	}

	sort.Strings(mounts)
	if len(mounts) > 0 {
		b.WriteString("    volumes:\n")
		for _, m := range mounts {
			b.WriteString("      - " + yamlString(m) + "\n")
		}
	}
	if len(tmpfs) > 0 {
		sort.Strings(tmpfs)
		b.WriteString("    tmpfs:\n")
		for _, t := range tmpfs {
			b.WriteString("      - " + yamlString(t) + "\n")
		}
	}
	if rwMounts > 0 {
		*warnings = append(*warnings, "the converted service shares writable mounts with the old container; stop the old container first if the app cannot run twice")
	}
	if len(externalVolumes) > 0 {
		names := make([]string, 0, len(externalVolumes))
		for n := range externalVolumes {
			names = append(names, n)
		}
		sort.Strings(names)
		return names
	}
	return nil
}

func writeEnvironment(b *strings.Builder, c inspectContainer) {
	env := make([]string, 0, len(c.Config.Env))
	for _, e := range c.Config.Env {
		key := e
		if i := strings.IndexByte(e, '='); i >= 0 {
			key = e[:i]
		}
		// PATH and HOSTNAME come from the image/runtime, not the operator.
		if key == "PATH" || key == "HOSTNAME" || key == "HOME" {
			continue
		}
		env = append(env, e)
	}
	if len(env) == 0 {
		return
	}
	sort.Strings(env)
	b.WriteString("    environment:\n")
	for _, e := range env {
		b.WriteString("      - " + yamlString(e) + "\n")
	}
}

func writeLabels(b *strings.Builder, c inspectContainer) {
	if len(c.Config.Labels) == 0 {
		return
	}
	keys := make([]string, 0, len(c.Config.Labels))
	for k := range c.Config.Labels {
		// Compose injects its own bookkeeping labels (project, config hash,
		// one-off flag…). Copying them would confuse the new project.
		if strings.HasPrefix(k, "com.docker.compose.") {
			continue
		}
		keys = append(keys, k)
	}
	sort.Strings(keys)
	b.WriteString("    labels:\n")
	for _, k := range keys {
		b.WriteString("      " + yamlString(k) + ": " + yamlString(c.Config.Labels[k]) + "\n")
	}
}

// writeNetwork preserves host/none/container network modes and external
// networks. The default bridge is omitted so Compose creates its own network.
// It returns the external network names that must be declared at file level.
func writeNetwork(b *strings.Builder, c inspectContainer, warnings *[]string) []string {
	mode := strings.TrimSpace(c.HostConfig.NetworkMode)
	switch mode {
	case "", "default", "bridge":
		// Compose gives the service its own network; nothing to emit.
		return nil
	case "host", "none":
		b.WriteString("    network_mode: " + yamlString(mode) + "\n")
		return nil
	}
	if strings.HasPrefix(mode, "container:") {
		b.WriteString("    network_mode: " + yamlString(mode) + "\n")
		*warnings = append(*warnings, "the container shared another container's network namespace ("+mode+"); the target container must exist before this project starts")
		return nil
	}

	var names []string
	for n := range c.NetworkSettings.Networks {
		if n == "bridge" || n == "host" || n == "none" {
			continue
		}
		names = append(names, n)
	}
	if len(names) == 0 {
		names = []string{mode}
	}
	sort.Strings(names)
	b.WriteString("    networks:\n")
	for _, n := range names {
		b.WriteString("      - " + yamlString(n) + "\n")
	}
	return names
}

// writeTopLevelVolumes declares named volumes as external so the new project
// reuses the existing data instead of creating empty prefixed volumes.
func writeTopLevelVolumes(b *strings.Builder, names []string) {
	if len(names) == 0 {
		return
	}
	b.WriteString("volumes:\n")
	for _, n := range names {
		b.WriteString("  " + yamlString(n) + ":\n")
		b.WriteString("    name: " + yamlString(n) + "\n")
		b.WriteString("    external: true\n")
	}
}

// writeTopLevelNetworks declares external networks shared with the original
// container.
func writeTopLevelNetworks(b *strings.Builder, names []string) {
	if len(names) == 0 {
		return
	}
	b.WriteString("networks:\n")
	for _, n := range names {
		b.WriteString("  " + yamlString(n) + ":\n")
		b.WriteString("    name: " + yamlString(n) + "\n")
		b.WriteString("    external: true\n")
	}
}

// occupiedHostPorts returns every host port published by any container,
// including the container being converted (which keeps running).
func occupiedHostPorts(ctx context.Context, u *updater) (map[int]bool, error) {
	out, err := u.runDocker(ctx, "", []string{"ps", "-a", "--format", "{{.Names}}\t{{.Ports}}"})
	if err != nil {
		return nil, err
	}
	occupied := map[int]bool{}
	for key := range parsePublishedPorts(out, "") {
		host, _, _ := strings.Cut(key, "/")
		if n, err := strconv.Atoi(host); err == nil {
			occupied[n] = true
		}
	}
	return occupied, nil
}

// freeContainerName returns a container name derived from base that is not
// used yet, so the converted project can run next to the original container.
func freeContainerName(ctx context.Context, u *updater, base string) (string, error) {
	out, err := u.runDocker(ctx, "", []string{"ps", "-a", "--format", "{{.Names}}"})
	if err != nil {
		return "", err
	}
	used := map[string]bool{}
	for _, line := range strings.Split(string(out), "\n") {
		if n := strings.TrimSpace(line); n != "" {
			used[n] = true
		}
	}
	for i := 1; ; i++ {
		candidate := base + "-compose"
		if i > 1 {
			candidate = base + "-compose-" + strconv.Itoa(i)
		}
		if !used[candidate] {
			return candidate, nil
		}
	}
}

// parsePublishedPorts extracts "<hostPort>/<proto>" -> container name from
// `docker ps --format '{{.Names}}\t{{.Ports}}'` output.
func parsePublishedPorts(out []byte, exclude string) map[string]string {
	used := map[string]string{}
	for _, line := range strings.Split(string(out), "\n") {
		name, ports, ok := strings.Cut(strings.TrimSpace(line), "\t")
		if !ok || name == exclude {
			continue
		}
		for _, entry := range strings.Split(ports, ",") {
			entry = strings.TrimSpace(entry)
			i := strings.Index(entry, "->")
			if i < 0 {
				continue
			}
			left := entry[:i]    // e.g. 0.0.0.0:8080
			right := entry[i+2:] // e.g. 80/tcp
			_, proto, _ := strings.Cut(right, "/")
			hostPort := left
			if j := strings.LastIndexByte(left, ':'); j >= 0 {
				hostPort = left[j+1:]
			}
			if hostPort == "" || proto == "" {
				continue
			}
			for _, hp := range expandPortRange(hostPort) {
				used[hp+"/"+proto] = name
			}
		}
	}
	return used
}

// expandPortRange turns "8080-8082" (as printed by `docker ps` for a published
// port range) into its individual ports. Non-ranges are returned unchanged.
func expandPortRange(s string) []string {
	start, end, ok := strings.Cut(s, "-")
	if !ok {
		return []string{s}
	}
	lo, err1 := strconv.Atoi(start)
	hi, err2 := strconv.Atoi(end)
	if err1 != nil || err2 != nil || hi < lo || hi-lo > 1000 {
		return []string{s}
	}
	ports := make([]string, 0, hi-lo+1)
	for p := lo; p <= hi; p++ {
		ports = append(ports, strconv.Itoa(p))
	}
	return ports
}

// composePortSpec builds a Compose short-syntax port mapping, omitting the
// protocol for tcp and the host IP when it is bound to all interfaces.
func composePortSpec(hostIP, hostPort, containerPort, proto string) string {
	spec := hostPort + ":" + containerPort
	if hostIP != "" && hostIP != "0.0.0.0" && hostIP != "::" {
		spec = hostIP + ":" + spec
	}
	if proto != "" && proto != "tcp" {
		spec += "/" + proto
	}
	return spec
}

// serviceName converts a container name into a valid Compose service name.
func serviceName(name string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(name) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '_', r == '.', r == '-':
			b.WriteRune(r)
		default:
			b.WriteByte('-')
		}
	}
	s := strings.Trim(b.String(), "-")
	if s == "" {
		return "converted"
	}
	return s
}

// yamlString quotes a scalar as a YAML double-quoted string. JSON string
// escaping is valid YAML, so encoding/json does the work.
func yamlString(s string) string {
	b, err := json.Marshal(s)
	if err != nil {
		return strconv.Quote(s)
	}
	return string(b)
}
